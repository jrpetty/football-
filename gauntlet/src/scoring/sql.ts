/**
 * The `sql` scorer ("Ask the Database"): the contestant answers a business question with one SQLite query.
 *
 * How a reply is marked
 *  1. The query is taken from the reply: the last ```sql block (else the last code block that starts with SELECT or
 *     WITH, else an unfenced query in the text). A trailing semicolon, comments and the fence itself don't matter.
 *  2. Safety: it must be ONE read-only statement that starts with SELECT or WITH. Anything that writes, attaches,
 *     changes settings, loads extensions, makes huge blobs or chains a second statement is refused before it runs
 *     (score 0). Defence in depth: it runs on an in-memory copy, in a separate Node process under the permission
 *     model, on a query_only connection, with a hard time limit and a row limit.
 *  3. The test's database is built from the schema and rows stored in the test (never an answer), once for the
 *     "live" database the prompt samples and once for each hidden copy: same tables, different data, generated by
 *     the same generator. The reference query and the contestant's query run on every database.
 *  4. Per database the two results are compared: the column count must match (names never matter, and the
 *     columns may come in any order); numbers are equal within the case's tolerance (default ±0.01, integers and
 *     reals alike, numeric text counts as a number); NULL equals only NULL; text is compared exactly after
 *     trimming. Rows are compared as a multiset (duplicates count) unless the question asks for an order.
 *     Database score = rows right ÷ the larger of the two row counts, halved when the question asks for an
 *     order and the rows that are right come in the wrong order. Wrong column count, an error, a time-out or too
 *     many rows score 0 on that database.
 *  5. The case score is the mean over all databases, so a query that hard-codes the sample's answer scores at most
 *     one database's share, and a query that is right on every database scores 1.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractCodeBlocks } from '../core/extract.ts';
import type { ScoreBreakdownItem, ScoreDetail, SqlDatabase, SqlExpected, SqlScorerSpec } from '../core/types.ts';

export type { SqlDatabase, SqlExpected, SqlScorerSpec, SqlTable } from '../core/types.ts';
import { runSandboxWorker } from './code-sandbox.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
export const SQL_WORKER = join(HERE, 'sql-worker.mjs');

/** Source hash of the scorer and its worker: part of the hash of every test that uses the sql scorer. */
let sourceHash: string | null = null;
export function sqlScorerSourceHash(): string {
  if (sourceHash) return sourceHash;
  const h = createHash('sha256');
  for (const f of [fileURLToPath(import.meta.url), SQL_WORKER]) h.update(readFileSync(f, 'utf8').replace(/\r\n/g, '\n'));
  sourceHash = h.digest('hex').slice(0, 12);
  return sourceHash;
}

// ─────────────────────────────── Extraction ───────────────────────────────

const SQL_LANGS = new Set(['sql', 'sqlite', 'sqlite3', 'postgresql', 'postgres', 'psql', 'mysql', 'tsql', 'plsql']);
const STARTS_SQL = /^\s*(?:(?:--[^\n]*\n|\/\*[\s\S]*?\*\/)\s*)*\(?\s*(?:WITH|SELECT)\b/i;

/**
 * The query candidates in a reply, most likely first: the last SQL-labelled block; else the last code block that
 * starts with SELECT/WITH; else unfenced text from the last line that starts a query (cut at a semicolon, and at
 * each blank line, so prose after the query is not part of it). The worker runs the first candidate that works.
 */
export function extractSqlCandidates(response: string): string[] {
  const blocks = extractCodeBlocks(response);
  for (let i = blocks.length - 1; i >= 0; i--) if (SQL_LANGS.has(blocks[i]!.lang) && blocks[i]!.code.trim()) return [blocks[i]!.code.trim()];
  for (let i = blocks.length - 1; i >= 0; i--) if (STARTS_SQL.test(blocks[i]!.code)) return [blocks[i]!.code.trim()];
  // Unfenced: the last line that begins a query (optionally after "FINAL ANSWER:" or "Query:").
  const text = response.replace(/```[^\n]*\n?/g, '\n');
  const starts = [...text.matchAll(/(?:^|\n)[ \t>*]*(?:(?:final\s+answer|answer|query|sql)\s*[:：]\s*)?(?=(?:WITH|SELECT)\b)/gi)];
  if (!starts.length) return [];
  const m = starts[starts.length - 1]!;
  let rest = text.slice(m.index! + m[0].length);
  const semi = statementEnd(rest);
  if (semi >= 0) rest = rest.slice(0, semi);
  const out = [rest.trim()];
  // Also offer the text cut at each blank line (longest first), in case prose follows the query.
  const cuts = [...rest.matchAll(/\n[ \t]*\n/g)].map((x) => x.index!).reverse();
  for (const c of cuts) out.push(rest.slice(0, c).trim());
  return [...new Set(out.filter(Boolean))].slice(0, 8);
}

/** Index of the first semicolon outside strings, quoted names and comments, or -1. */
function statementEnd(sql: string): number {
  const sk = skeleton(sql);
  return sk.indexOf(';');
}

// ─────────────────────────────── Safety ───────────────────────────────

/**
 * The query with string literals, quoted names and comments blanked (same length, so positions line up), for the
 * keyword checks. Unterminated literals blank to the end.
 */
export function skeleton(sql: string): string {
  let out = '';
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const ch = sql[i]!;
    const next = sql[i + 1];
    if (ch === '-' && next === '-') {
      const end = sql.indexOf('\n', i);
      const stop = end < 0 ? n : end;
      out += ' '.repeat(stop - i);
      i = stop;
    } else if (ch === '/' && next === '*') {
      const end = sql.indexOf('*/', i + 2);
      const stop = end < 0 ? n : end + 2;
      out += ' '.repeat(stop - i);
      i = stop;
    } else if (ch === "'" || ch === '"' || ch === '`' || ch === '[') {
      const close = ch === '[' ? ']' : ch;
      let j = i + 1;
      while (j < n) {
        if (sql[j] === close) {
          if (close !== ']' && sql[j + 1] === close) {
            j += 2;
            continue;
          }
          break;
        }
        j++;
      }
      const stop = Math.min(n, j + 1);
      out += (ch === "'" ? "'" : '"') + ' '.repeat(Math.max(0, stop - i - 2)) + (stop - i >= 2 ? (ch === "'" ? "'" : '"') : '');
      i = stop;
    } else {
      out += ch;
      i++;
    }
  }
  return out;
}

const FORBIDDEN: Array<[RegExp, string]> = [
  [/\b(?:INSERT|UPDATE|DELETE|UPSERT|MERGE|TRUNCATE)\b/i, 'it changes data'],
  [/\bREPLACE\s+INTO\b|\bINSERT\s+OR\b/i, 'it changes data'],
  [/\b(?:CREATE|DROP|ALTER|REINDEX|VACUUM|ANALYZE)\b/i, 'it changes the database structure'],
  [/\b(?:ATTACH|DETACH)\b/i, 'it attaches another database'],
  [/\bPRAGMA\b/i, 'it changes database settings (PRAGMA)'],
  [/\b(?:BEGIN|COMMIT|ROLLBACK|SAVEPOINT|RELEASE|END\s+TRANSACTION)\b/i, 'it controls transactions'],
  [/\bload_extension\b/i, 'it loads an extension'],
  [/\b(?:randomblob|zeroblob)\b/i, 'it builds large blobs'],
  [/\bEXPLAIN\b/i, 'it is an EXPLAIN statement, not a query'],
];

export const MAX_QUERY_CHARS = 20_000;

/** Null when the query is one read-only SELECT/WITH statement; otherwise the plain reason it is refused. */
export function unsafeReason(sql: string): string | null {
  if (sql.length > MAX_QUERY_CHARS) return `it is longer than ${MAX_QUERY_CHARS.toLocaleString('en-GB')} characters`;
  const sk = skeleton(sql).replace(/[\s;]+$/, '');
  if (!sk.trim()) return 'there is no query';
  if (sk.includes(';')) return 'it contains more than one statement';
  if (!/^\s*\(?\s*(?:WITH|SELECT)\b/i.test(sk)) return 'it does not start with SELECT or WITH';
  for (const [re, why] of FORBIDDEN) if (re.test(sk)) return why;
  return null;
}

/** The query as it is run: trailing semicolons removed. */
function runnable(sql: string): string {
  const sk = skeleton(sql);
  const trimmed = sk.replace(/[\s;]+$/, '');
  return sql.slice(0, trimmed.length);
}

// ─────────────────────────────── Comparison ───────────────────────────────

export type Cell = string | number | null;

export interface ResultSet {
  columns: string[];
  rows: Cell[][];
}

const NUMERIC_TEXT = /^\s*[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?\s*$/;

function asNumber(v: Cell): number | null {
  if (typeof v === 'number') return v;
  if (typeof v === 'string' && NUMERIC_TEXT.test(v)) return Number(v);
  return null;
}

/** Whether two cells are equal: NULL only equals NULL; numbers (or numeric text) within `tol`; text exact after trimming. */
export function cellsEqual(ref: Cell, got: Cell, tol: number): boolean {
  if (ref === null || got === null) return ref === null && got === null;
  const a = asNumber(ref);
  const b = asNumber(got);
  if (typeof ref === 'number' || typeof got === 'number') {
    if (a === null || b === null) return false;
    return Math.abs(a - b) <= tol + 1e-9 * Math.max(1, Math.abs(a));
  }
  return String(ref).trim() === String(got).trim();
}

function* permutations(n: number): Generator<number[]> {
  const p = Array.from({ length: n }, (_, i) => i);
  const c = new Array(n).fill(0);
  yield p.slice();
  let i = 0;
  while (i < n) {
    if (c[i] < i) {
      const k = i % 2 ? c[i] : 0;
      [p[i], p[k]] = [p[k]!, p[i]!];
      yield p.slice();
      c[i]++;
      i = 0;
    } else {
      c[i] = 0;
      i++;
    }
  }
}

interface Match {
  matched: number;
  inOrder: boolean;
  perm: number[];
}

/** Rows of `got` (columns reordered by `perm`) matched to rows of `ref`, greedily in `got` order. */
function matchRows(ref: Cell[][], got: Cell[][], perm: number[], tol: number): Match {
  const used = new Array(ref.length).fill(false);
  let matched = 0;
  let last = -1;
  let inOrder = true;
  for (const g of got) {
    const row = perm.map((j) => g[j]!);
    // Prefer the first unused reference row at or after the last match (keeps an ordered answer in order).
    let hit = -1;
    for (let k = 0; k < ref.length && hit < 0; k++) {
      const idx = (last + 1 + k) % ref.length;
      if (!used[idx] && row.every((v, c) => cellsEqual(ref[idx]![c]!, v, tol))) hit = idx;
    }
    if (hit >= 0) {
      used[hit] = true;
      matched++;
      if (hit < last) inOrder = false;
      last = hit;
    }
  }
  return { matched, inOrder, perm };
}

/** The column orders worth trying: identity first, then (for up to 7 columns) the ones whose columns share most values. */
function candidatePerms(ref: Cell[][], got: Cell[][], n: number, tol: number): number[][] {
  const identity = Array.from({ length: n }, (_, i) => i);
  if (n <= 1 || n > 7 || !ref.length || !got.length) return [identity];
  // overlap[i][j]: how many sample rows agree when model column j stands in for reference column i.
  const sampleRef = ref.slice(0, 60);
  const sampleGot = got.slice(0, 60);
  const overlap = Array.from({ length: n }, (_, i) =>
    Array.from({ length: n }, (_, j) => {
      let hits = 0;
      for (const r of sampleRef) if (sampleGot.some((g) => cellsEqual(r[i]!, g[j]!, tol))) hits++;
      return hits;
    }),
  );
  let best: Array<{ p: number[]; s: number }> = [];
  for (const p of permutations(n)) {
    const s = p.reduce((sum, j, i) => sum + overlap[i]![j]!, 0);
    best.push({ p, s });
    if (best.length > 64) {
      best.sort((a, b) => b.s - a.s);
      best = best.slice(0, 8);
    }
  }
  best.sort((a, b) => b.s - a.s);
  return [identity, ...best.slice(0, 8).map((b) => b.p)];
}

export interface DbComparison {
  score: number;
  matched: number;
  refRows: number;
  gotRows: number;
  reason: string;
}

/** Compare one database's result with the reference (see the header for the rule). */
export function compareResults(ref: ResultSet, got: ResultSet, opts: { ordered: boolean; tolerance: number }): DbComparison {
  const n = ref.columns.length;
  if (got.columns.length !== n) {
    return { score: 0, matched: 0, refRows: ref.rows.length, gotRows: got.rows.length, reason: `${got.columns.length} column${got.columns.length === 1 ? '' : 's'} instead of ${n}` };
  }
  if (!ref.rows.length && !got.rows.length) return { score: 1, matched: 0, refRows: 0, gotRows: 0, reason: 'no rows, as expected' };
  let best: Match = { matched: -1, inOrder: true, perm: [] };
  for (const p of candidatePerms(ref.rows, got.rows, n, opts.tolerance)) {
    const m = matchRows(ref.rows, got.rows, p, opts.tolerance);
    if (m.matched > best.matched || (m.matched === best.matched && m.inOrder && !best.inOrder)) best = m;
    if (best.matched === ref.rows.length && best.matched === got.rows.length && (!opts.ordered || best.inOrder)) break;
  }
  const denom = Math.max(ref.rows.length, got.rows.length);
  const share = denom ? best.matched / denom : 0;
  const orderPenalty = opts.ordered && best.matched > 1 && !best.inOrder;
  const score = orderPenalty ? share / 2 : share;
  const reason =
    best.matched === ref.rows.length && best.matched === got.rows.length
      ? orderPenalty
        ? 'right rows, wrong order (half marks)'
        : 'exact match'
      : `${best.matched} of ${ref.rows.length} rows right${got.rows.length !== ref.rows.length ? `, ${got.rows.length} returned` : ''}${orderPenalty ? ', wrong order' : ''}`;
  return { score, matched: best.matched, refRows: ref.rows.length, gotRows: got.rows.length, reason };
}

// ─────────────────────────────── Running ───────────────────────────────

interface WorkerOut {
  ref?: ResultSet & { error?: string };
  model?: ResultSet & { error?: string; sql?: string; tooMany?: boolean };
  timedOut: boolean;
}

export async function runOnDatabase(spec: SqlScorerSpec, db: SqlDatabase, reference: string | null, candidates: string[], signal?: AbortSignal): Promise<WorkerOut> {
  const r = await runSandboxWorker(
    SQL_WORKER,
    { schema: spec.schema, tables: db.tables, reference, candidates, maxRows: spec.maxRows ?? 5000, maxCellChars: 500 },
    { hardLimitMs: spec.timeoutMs ?? 8000, signal },
  );
  const out: WorkerOut = { timedOut: r.killed };
  for (const line of r.stdout.split('\n')) {
    if (!line.trim()) continue;
    try {
      const m = JSON.parse(line) as Partial<WorkerOut>;
      if (m.ref) out.ref = m.ref;
      if (m.model) out.model = m.model;
    } catch {
      /* a torn line */
    }
  }
  return out;
}

/** Run the reference query alone on every database (generators, tests). */
export async function referenceResults(spec: SqlScorerSpec, reference: string): Promise<ResultSet[]> {
  const outs = await Promise.all(spec.databases.map((db) => runOnDatabase(spec, db, reference, [])));
  return outs.map((o, i) => {
    if (!o.ref || o.ref.error) throw new Error(`reference failed on ${spec.databases[i]!.id}: ${o.ref?.error ?? 'no result'}`);
    return { columns: o.ref.columns, rows: o.ref.rows };
  });
}

export interface SqlOutcome {
  score: number;
  passed: boolean;
  summary: string;
  detail: ScoreDetail;
}

function round4(n: number): number {
  return Math.round(n * 10000) / 10000;
}

export async function scoreSql(spec: SqlScorerSpec, expected: SqlExpected, response: string, signal?: AbortSignal): Promise<SqlOutcome> {
  const candidates = extractSqlCandidates(response);
  if (!candidates.length) return { score: 0, passed: false, summary: 'No SQL query found', detail: { formatOk: false } };
  const safe = candidates.map((c) => ({ c, why: unsafeReason(c) }));
  const runnableCandidates = safe.filter((s) => !s.why).map((s) => runnable(s.c));
  if (!runnableCandidates.length) {
    const why = safe[0]!.why!;
    return {
      score: 0,
      passed: false,
      summary: `Query refused: ${why}`,
      detail: { formatOk: true, extracted: candidates[0]!.slice(0, 20000), notes: `Only one read-only SELECT or WITH statement is allowed; this one was refused because ${why}. Nothing was run.` },
    };
  }
  const tol = expected.tolerance ?? spec.tolerance ?? 0.01;
  const ordered = Boolean(expected.ordered);
  const outs = await Promise.all(spec.databases.map((db) => runOnDatabase(spec, db, expected.reference, runnableCandidates, signal)));
  const items: ScoreBreakdownItem[] = [];
  let total = 0;
  let ran: string | undefined;
  let firstError: string | undefined;
  for (let i = 0; i < outs.length; i++) {
    const o = outs[i]!;
    const db = spec.databases[i]!;
    const label = db.id === 'live' ? 'live database (sampled in the prompt)' : `hidden copy ${db.id}`;
    if (!o.ref || o.ref.error) throw new Error(`sql scorer: the reference query failed on ${db.id}: ${o.ref?.error ?? (o.timedOut ? 'time limit' : 'no result')}`);
    if (!o.model) {
      items.push({ label, passed: false, detail: o.timedOut ? `stopped: over the ${((spec.timeoutMs ?? 8000) / 1000).toFixed(0)} s time limit` : 'no result' });
      firstError ??= o.timedOut ? 'time limit' : 'no result';
      continue;
    }
    if (o.model.error) {
      items.push({ label, passed: false, detail: `error: ${o.model.error.slice(0, 200)}` });
      firstError ??= o.model.error;
      continue;
    }
    ran ??= o.model.sql;
    const c = compareResults(o.ref, o.model, { ordered, tolerance: tol });
    total += c.score;
    items.push({ label, passed: c.score === 1, detail: `${c.reason}${c.score > 0 && c.score < 1 ? ` (${Math.round(c.score * 100)}%)` : ''}` });
  }
  const score = round4(total / spec.databases.length);
  const perfect = items.filter((x) => x.passed).length;
  const summary =
    perfect === items.length
      ? `Correct on all ${items.length} databases`
      : firstError && total === 0
        ? `Query failed: ${firstError.slice(0, 80)}`
        : `${perfect}/${items.length} databases exactly right · score ${Math.round(score * 100)}%`;
  return {
    score,
    passed: perfect === items.length,
    summary,
    detail: { formatOk: true, items, extracted: (ran ?? runnableCandidates[0]!).slice(0, 20000), expected: expected.reference },
  };
}
