def jsonable(x):
    return json.loads(json.dumps(x))


MISSING = object()


def leaves(x, keys=()):
    """(key tuple, value) for every scored leaf; a list is one unit (its length and items share a weight)."""
    if isinstance(x, dict) and x:
        for k, v in x.items():
            yield from leaves(v, keys + (k,))
    else:
        yield keys, x


def at(x, keys):
    for k in keys:
        if not isinstance(x, dict) or k not in x:
            return MISSING
        x = x[k]
    return x


def norm(v):
    return sorted(json.dumps(i) for i in v) if isinstance(v, list) else v


def trap_weights(expected, careless, W, sets, extra=()):
    """Weight W on every field a careless reading gets wrong (the fields where a trap sits: a corrected deadline, a
    duplicate, a scam, a renumbered clause, a keyed-in error...), 1 on routine fields. Inside an id-keyed set every
    field gets an explicit weight, and the set's own weight W prices an invented item."""
    w = {}
    for keys, v in leaves(expected):
        path = '.'.join(keys)
        in_set = keys[0] in sets
        trap = norm(at(careless, keys)) != norm(v) or keys in extra
        if trap:
            w[path] = W
        elif in_set:
            w[path] = 1
    for sp in sets:
        w[sp] = W
    return w


def finish(meta, cases, notes_fn):
    out = []
    W = meta.pop('trap_weight', None)
    above = meta.pop('above_constant', None)
    for c in cases:
        exp = jsonable(c['expected'])
        row = dict(id=c['id'], prompt=c['prompt'], expected=exp)
        if W:
            sc = dict(meta['scorer'])
            sc['weights'] = trap_weights(exp, jsonable(c['careless']), W, list(sc.get('sets', {})), set(c.get('traps', ())))
            if above:
                sc['aboveConstant'] = above
            row['scorer'] = sc
        row['notes'] = f"[{c['tier']}] " + notes_fn(c) + (f" Fields where a trap sits are worth {W} points, routine fields 1." if W else '')
        out.append(row)
    avg_in = int(sum(tok(c['prompt']) for c in out) / len(out))
    meta['estimate'] = {'inputTokens': avg_in, 'outputTokens': meta.pop('out_tokens')}
    path = write_test(meta, out)
    return path, out


